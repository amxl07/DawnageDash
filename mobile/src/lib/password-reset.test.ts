import * as Linking from 'expo-linking';

import { requestPasswordReset } from './password-reset';

jest.mock('expo-linking', () => ({ createURL: jest.fn() }));

const mockCreateURL = jest.mocked(Linking.createURL);

describe('requestPasswordReset', () => {
  it.each([
    ['Expo Go', 'exp://192.0.2.1:8081/--/reset-password'],
    ['development', 'dawnage-dev://reset-password'],
    ['preview', 'dawnage-preview://reset-password'],
    ['production', 'dawnage://reset-password'],
  ])('passes the active %s redirect generated by Expo to Supabase', async (_runtime, redirectTo) => {
    mockCreateURL.mockReturnValue(redirectTo);
    const resetPasswordForEmail = jest.fn().mockResolvedValue({ data: {}, error: null });

    await expect(requestPasswordReset({ resetPasswordForEmail }, 'client@example.test'))
      .resolves.toEqual({ data: {}, error: null });

    expect(mockCreateURL).toHaveBeenCalledWith('reset-password');
    expect(resetPasswordForEmail).toHaveBeenCalledWith('client@example.test', { redirectTo });
  });
});
